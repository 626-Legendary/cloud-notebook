import { test, expect } from "@playwright/test";

test("home cards, cover crop/zoom/cancel, brand navigation, sidebar hierarchy and title rename work together", async ({ page, baseURL }, testInfo) => {
  if (process.env.E2E_ALLOW_MUTATIONS !== "1" || baseURL !== "http://127.0.0.1:3002") throw new Error("Disposable 3002 server required");
  const headers = { Origin: baseURL }, password = "BrowserTest12345";
  expect((await page.request.post("/api/auth/register", { headers, data: { username: `home_${Date.now()}`, password, confirmPassword: password } })).status()).toBe(201);
  await page.goto("/app");
  await expect(page.getByText("开始记录你的想法", { exact: true })).toBeVisible();
  const { folder } = await (await page.request.post("/api/folders", { headers, data: { name: "项目文件夹" } })).json();
  const { notebook } = await (await page.request.post("/api/notebooks", { headers, data: { title: "封面与首页", folderId: folder.id } })).json();
  const { notebook: root } = await (await page.request.post("/api/notebooks", { headers, data: { title: "默认位置" } })).json();
  await page.request.post(`/api/notebooks/${notebook.id}/pages`, { headers, data: { title: "首页编辑测试" } });
  await page.request.post("/api/pins", { headers, data: { type: "notebook", id: notebook.id } });
  await page.reload();
  await expect(page.locator(".notebook-home-card")).toHaveCount(2);
  await expect(page.locator(".notebook-home-cover svg.lucide-notebook-pen")).toHaveCount(2);
  const newButton = await page.locator(".workspace-new-button").boundingBox();
  const pinned = await page.locator(".pinned-section").boundingBox();
  const label = await page.locator(".workspace-section-label").boundingBox();
  expect(newButton!.y).toBeGreaterThanOrEqual(pinned!.y + pinned!.height);
  expect(label!.y).toBeGreaterThanOrEqual(newButton!.y + newButton!.height);
  await page.getByRole("button", { name: "打开笔记本：封面与首页", exact: true }).click();
  await expect(page.locator(".notebook-row.selected svg.lucide-notebook-pen")).toHaveCount(1);
  const nested = page.locator(".folder-section").filter({ has: page.getByRole("button", { name: "项目文件夹", exact: true }) }).locator(".notebook-icon");
  const folderIcon = page.locator(".folder-section").filter({ has: page.getByRole("button", { name: "项目文件夹", exact: true }) }).locator(".folder-row > .folder-icon");
  expect((await nested.boundingBox())!.x).toBeGreaterThan((await folderIcon.boundingBox())!.x);
  await expect(page.getByRole("button", { name: "下载 Markdown", exact: true })).toHaveCount(0);
  await expect(page.getByLabel("导入 Markdown 文件", { exact: true })).toHaveCount(0);
  await expect(page.getByTitle("导出 / 打印", { exact: true })).toBeVisible();
  await page.getByTitle("编辑封面", { exact: true }).click();
  const edit = page.getByRole("dialog", { name: "编辑封面", exact: true });
  const sourceImage = await page.evaluate(() => {
    const canvas = document.createElement("canvas"); canvas.width = 400; canvas.height = 200;
    const context = canvas.getContext("2d")!;
    context.fillStyle = "#ff0000"; context.fillRect(0, 0, 200, 200);
    context.fillStyle = "#0000ff"; context.fillRect(200, 0, 200, 200);
    return canvas.toDataURL("image/png").split(",")[1];
  });
  await edit.getByLabel("选择封面图片").setInputFiles({ name: "crop-regions.png", mimeType: "image/png", buffer: Buffer.from(sourceImage, "base64") });
  const crop = page.getByRole("dialog", { name: "裁剪笔记本封面", exact: true });
  await expect(crop.getByRole("img", { name: "裁剪预览", exact: true })).toBeVisible();
  await crop.getByLabel("封面缩放").fill("2");
  const viewport = crop.getByRole("group"); const box = (await viewport.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 20); await page.mouse.up();
  await viewport.focus(); await page.keyboard.press("ArrowRight");
  await page.screenshot({ path: testInfo.outputPath("cover-crop-desktop.png") });
  await crop.getByRole("button", { name: "确认裁剪", exact: true }).click();
  await edit.getByRole("button", { name: "保存", exact: true }).click();
  await expect(edit).not.toBeVisible();
  const saved = (await (await page.request.get(`/api/notebooks/${notebook.id}`)).json()).notebook;
  const img = page.locator(".notebook-cover-card img");
  await expect.poll(() => img.evaluate((element) => ({ width: (element as HTMLImageElement).naturalWidth, height: (element as HTMLImageElement).naturalHeight }))).toEqual({ width: 1600, height: 860 });
  await page.reload(); await expect(img).toBeVisible();
  const pixels = await img.evaluate((element) => {
    const image = element as HTMLImageElement;
    const canvas = document.createElement("canvas"); canvas.width = 1600; canvas.height = 860;
    const context = canvas.getContext("2d")!; context.drawImage(image, 0, 0);
    return [40, 800, 1560].map((x) => Array.from(context.getImageData(x, 430, 1, 1).data));
  });
  // Distinct pixels prove persisted cropped bytes and the chosen pan/zoom, not just dimensions.
  expect(pixels[0][0]).toBeGreaterThan(230);
  expect(pixels[1][0]).toBeGreaterThan(230);
  expect(pixels[2][2]).toBeGreaterThan(230);
  await page.getByTitle("编辑封面", { exact: true }).click();
  await edit.getByLabel("选择封面图片").setInputFiles("tests/fixtures/cover.png");
  await crop.getByRole("button", { name: "取消", exact: true }).click();
  await expect(edit.getByRole("button", { name: "保存", exact: true })).toBeDisabled();
  await edit.getByRole("button", { name: "取消", exact: true }).click();
  expect((await (await page.request.get(`/api/notebooks/${notebook.id}`)).json()).notebook.coverAssetId).toBe(saved.coverAssetId);
  await page.getByLabel("封面与首页 操作", { exact: true }).click();
  await page.getByRole("menuitem", { name: "重命名", exact: true }).click();
  await page.getByRole("dialog", { name: "重命名笔记本", exact: true }).getByRole("textbox").fill("更新后的笔记本");
  await page.getByRole("dialog", { name: "重命名笔记本", exact: true }).getByRole("button", { name: "保存", exact: true }).click();
  await expect(page.locator(".pages-panel-title")).toHaveText("更新后的笔记本");
  await page.locator(".brand-home-link").click();
  await expect(page.getByRole("button", { name: "打开笔记本：更新后的笔记本", exact: true })).toBeVisible();
  await page.goBack(); await expect(page.locator(".pages-panel-title")).toHaveText("更新后的笔记本");
  await page.locator(".brand-home-link").click();
  await page.getByRole("button", { name: "打开笔记本：默认位置", exact: true }).click();
  await expect(page.locator(".pages-panel-title")).toHaveText(root.title);
  await page.reload(); await expect(page.locator(".pages-panel-title")).toHaveText(root.title);
  await page.locator(".brand-home-link").click();
  await page.getByRole("button", { name: "账号与设置", exact: true }).click();
  await page.getByRole("menuitem", { name: "外观", exact: true }).hover();
  await page.getByRole("menuitemradio", { name: "深色", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator("html")).toHaveClass(/dark/);
  expect(await page.locator(".notebook-home").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await expect.poll(() => page.locator(".sidebar").evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: testInfo.outputPath("notebook-home-mobile-dark.png"), fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.locator(".notebook-home").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  // The original creation form also accepts a cover: it must use the same crop flow.
  await page.getByRole("button", { name: "新建笔记本", exact: true }).click();
  const create = page.getByRole("dialog", { name: "新建笔记本", exact: true });
  await create.getByLabel("笔记本名称").fill("创建时裁剪封面");
  await create.getByLabel("封面图片").setInputFiles("tests/fixtures/cover.png");
  await crop.getByRole("button", { name: "取消", exact: true }).click();
  expect((await (await page.request.get("/api/notebooks")).json()).notebooks).toHaveLength(2);
  await create.getByLabel("封面图片").setInputFiles("tests/fixtures/cover.png");
  await crop.getByRole("button", { name: "确认裁剪", exact: true }).click();
  await create.getByRole("button", { name: "创建笔记本", exact: true }).click();
  await expect(page.locator(".pages-panel-title")).toHaveText("创建时裁剪封面");
  await expect.poll(() => page.locator(".notebook-cover-card img").evaluate((element) => (element as HTMLImageElement).naturalWidth)).toBe(1600);

});
