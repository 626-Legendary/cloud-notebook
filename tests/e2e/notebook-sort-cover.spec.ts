import { test, expect } from "@playwright/test";

test("Notebook downward sort menu and accessible cover upload", async ({ page, baseURL }, testInfo) => {
  if (process.env.E2E_ALLOW_MUTATIONS !== "1" || new URL(baseURL!).port !== "3002") throw new Error("Disposable 3002 server required");
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const headers = { Origin: baseURL! };
  const registered = await page.request.post("/api/auth/register", { headers, data: { username: `v1024_${Date.now()}`, password: "BrowserTest12345", confirmPassword: "BrowserTest12345" } });
  expect(registered.status()).toBe(201);
  const { notebook } = await (await page.request.post("/api/notebooks", { headers, data: { title: "排序与封面" } })).json();
  for (const title of ["Zulu", "Alpha"]) expect((await page.request.post(`/api/notebooks/${notebook.id}/pages`, { headers, data: { title } })).ok()).toBeTruthy();
  await page.goto("/app");
  await page.getByRole("button", { name: "排序与封面", exact: true }).click();
  const sort = page.getByRole("button", { name: "页面排序方式", exact: true });
  await expect(sort).toContainText("手动排序");
  await expect(page.locator(".pages-panel select")).toHaveCount(0);
  const triggerBox = (await sort.boundingBox())!;
  await sort.click();
  await expect(page.getByRole("menuitemradio", { name: "手动排序" })).toHaveAttribute("aria-checked", "true");
  expect((await page.locator(".page-sort-menu").boundingBox())!.y).toBeGreaterThanOrEqual(triggerBox.y + triggerBox.height);
  await page.getByRole("menuitemradio", { name: "标题", exact: true }).click();
  await expect(sort).toContainText("标题");
  await expect(page.locator(".page-list .page-row-title")).toHaveText(["Alpha", "Zulu"]);
  await page.keyboard.press("Tab");
  await sort.focus();
  await expect(sort).toHaveCSS("outline-style", "solid");
  await page.keyboard.press("Enter");
  await expect(page.getByRole("menuitemradio", { name: "标题", exact: true })).toHaveAttribute("aria-checked", "true");
  await page.keyboard.press("Escape"); await expect(sort).toBeFocused();
  await page.getByTitle("编辑封面", { exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "编辑封面", exact: true });
  await expect(dialog).toHaveAccessibleDescription("支持 JPG、PNG、WebP、GIF，裁剪确认后点击保存生效。");
  const upload = dialog.getByRole("button", { name: "上传封面", exact: true });
  await expect(upload).toBeVisible();
  await expect(upload).toHaveCSS("display", /^(inline-)?flex$/);
  await upload.focus();
  const chooserPromise = page.waitForEvent("filechooser");
  await page.keyboard.press("Enter");
  const chooser = await chooserPromise;
  const file = { name: "cover.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=", "base64") };
  await chooser.setFiles(file);
  await page.getByRole("dialog", { name: "裁剪笔记本封面", exact: true }).getByRole("button", { name: "确认裁剪", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("cover-裁剪.webp");
  await expect(dialog.getByAltText("所选封面预览")).toBeVisible();
  const repeatChooserPromise = page.waitForEvent("filechooser");
  await dialog.getByRole("button", { name: "重新选择" }).click();
  await (await repeatChooserPromise).setFiles(file);
  await page.getByRole("dialog", { name: "裁剪笔记本封面", exact: true }).getByRole("button", { name: "确认裁剪", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("cover-裁剪.webp");
  await dialog.getByLabel("选择封面图片").setInputFiles({ name: "invalid.txt", mimeType: "text/plain", buffer: Buffer.from("invalid") });
  await expect(page.getByText("请选择有效的 JPG、PNG、WebP 或 GIF 图片", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("status")).toHaveText("cover-裁剪.webp");
  await page.screenshot({ path: testInfo.outputPath("cover-desktop.png") });
  let uploads = 0;
  await page.route("**/api/assets/upload", async (route) => { uploads++; await new Promise((resolve) => setTimeout(resolve, 500)); await route.continue(); });
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "保存中…" })).toBeDisabled();
  await expect(dialog.getByRole("button", { name: "取消", exact: true })).toBeDisabled();
  await expect(dialog).not.toBeVisible(); expect(uploads).toBe(1);
  const saved = (await (await page.request.get("/api/notebooks")).json()).notebooks.find((item: { id: string }) => item.id === notebook.id);
  expect(saved.coverAssetId).toBeTruthy();
  await page.getByTitle("编辑封面", { exact: true }).click();
  await dialog.getByRole("button", { name: "移除封面" }).click();
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByTitle("编辑封面", { exact: true }).click();
  await expect(dialog.getByAltText("排序与封面当前封面")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath("cover-mobile.png") });
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await dialog.getByRole("button", { name: "移除封面" }).click();
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const after = (await (await page.request.get("/api/notebooks")).json()).notebooks.find((item: { id: string }) => item.id === notebook.id);
  expect(after.coverAssetId).toBeNull();
  expect(errors).toEqual([]);
});
