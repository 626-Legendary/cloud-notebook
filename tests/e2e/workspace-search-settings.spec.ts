import { test, expect } from "@playwright/test";

test("workspace refinements: stable search, refresh, dark highlight and settings menus", async ({ page, baseURL }, testInfo) => {
  if (process.env.E2E_ALLOW_MUTATIONS !== "1" || !["3001", "3002"].includes(new URL(baseURL!).port)) throw new Error("Disposable test server required");
  const headers = { Origin: baseURL! };
  const username = `refine_${Date.now()}`;
  expect((await page.request.post("/api/auth/register", { headers, data: { username, password: "BrowserTest12345", confirmPassword: "BrowserTest12345" } })).ok()).toBeTruthy();
  const { notebook } = await (await page.request.post("/api/notebooks", { headers, data: { title: "Refinement notebook" } })).json();
  await page.request.post(`/api/notebooks/${notebook.id}/pages`, { headers, data: { title: "First page" } });
  const { page: note } = await (await page.request.post(`/api/notebooks/${notebook.id}/pages`, { headers, data: { title: "Continue this second page" } })).json();
  expect((await page.request.patch(`/api/pages/${note.id}`, { headers, data: { version: note.version, content: { type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text: "蓝色高亮正文", marks: [{ type: "highlight", attrs: { color: "#BFDBFE" } }] }] }] } } })).ok()).toBeTruthy();
  await page.request.post("/api/pins", { headers, data: { type: "page", id: note.id } });
  await page.request.post("/api/folders", { headers, data: { name: "Rename icon folder" } });
  await page.goto(`/app?page=${note.id}`);
  await expect(page.getByLabel("页面标题", { exact: true })).toHaveValue("Continue this second page");
  await page.reload();
  await expect(page.getByLabel("页面标题", { exact: true })).toHaveValue("Continue this second page");
  await expect(page.locator(".notebook-editor")).toContainText("蓝色高亮正文");
  expect(new URL(page.url()).searchParams.get("page")).toBe(note.id);
  await expect(page.locator(".pinned-item")).toHaveCSS("margin-left", "18px");
  await page.getByRole("button", { name: "Rename icon folder 操作", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: "重命名", exact: true }).locator("svg.lucide-pencil")).toHaveCount(1);
  await page.keyboard.press("Escape");
  const settings = page.getByRole("button", { name: "账号与设置", exact: true });
  await expect(settings.locator("svg.lucide-settings")).toHaveCount(1);
  await settings.click();
  await page.getByRole("menuitem", { name: "外观", exact: true }).hover();
  await expect(page.getByRole("menuitemradio", { name: "跟随系统", exact: true })).toHaveAttribute("aria-checked", "true");
  await page.getByRole("menuitemradio", { name: "深色", exact: true }).click();
  await expect(page.locator("html")).toHaveClass(/dark/);
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const mark = page.locator(".notebook-editor mark");
  await expect(mark).toHaveAttribute("data-color", "#BFDBFE");
  expect(await mark.evaluate((element) => getComputedStyle(element).backgroundColor)).toMatch(/0\.26/);
  await page.screenshot({ path: testInfo.outputPath("dark-highlight.png"), fullPage: true });
  await settings.click();
  await page.getByRole("menuitem", { name: "自动保存", exact: true }).hover();
  await expect(page.getByRole("menuitemradio", { name: "实时保存", exact: true })).toHaveAttribute("aria-checked", "true");
  await page.getByRole("menuitemradio", { name: "每 1 分钟", exact: true }).click();
  await expect.poll(async () => (await (await page.request.get("/api/settings")).json()).settings.autoSaveMode).toBe("60s");
  await settings.click();
  await page.getByRole("menuitem", { name: "自动保存", exact: true }).hover();
  await expect(page.getByRole("menuitemradio", { name: "每 1 分钟", exact: true })).toHaveAttribute("aria-checked", "true");
  await page.keyboard.press("Escape"); await page.keyboard.press("Escape");
  await settings.click();
  await page.getByRole("menuitem", { name: "账号信息", exact: true }).hover();
  await expect(page.locator(".account-info")).toContainText(username);
  await expect(page.locator(".account-info")).toContainText("注册时间");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("account-menu.png") });
  await page.keyboard.press("Escape"); await page.keyboard.press("Escape");
  await settings.click();
  await page.getByRole("menuitem", { name: "登录设备", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "登录设备", exact: true })).toBeVisible();
  await expect(page.locator(".current-device-badge")).toHaveText("当前设备");
  await expect(page.locator(".current-device-badge")).toHaveCSS("color", "rgb(147, 191, 159)");
  await page.screenshot({ path: testInfo.outputPath("devices-dialog.png") });
  await page.getByRole("button", { name: "关闭登录设备", exact: true }).click();
  await page.getByTitle("导出 / 打印", { exact: true }).click();
  await expect(page.locator(".export-options > label")).toHaveText(["当前页面", "当前笔记本"]);
  await page.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByTitle("全局搜索 (Ctrl/Cmd+Shift+F)").click();
  const dialog = page.getByRole("dialog", { name: "全局搜索", exact: true });
  const input = page.getByLabel("全局搜索词", { exact: true });
  const initial = await dialog.boundingBox(); const inputBox = await input.boundingBox();
  for (const query of ["蓝", "蓝色", "蓝色高亮", "不存在的内容"]) {
    const response = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/search" && new URL(response.url()).searchParams.get("q") === query);
    await input.fill(query); await response;
    await expect.poll(async () => (await dialog.boundingBox())!.height).toBe(initial!.height);
    expect((await dialog.boundingBox())!.y).toBe(initial!.y);
    expect((await input.boundingBox())!.y).toBe(inputBox!.y);
  }
  await page.screenshot({ path: testInfo.outputPath("stable-search.png") });
  await page.getByRole("button", { name: "关闭搜索", exact: true }).click();
  const saved = (await (await page.request.get(`/api/pages/${note.id}`)).json()).page;
  expect(saved.content).toContain('"color":"#BFDBFE"');
  expect(saved.content).not.toContain("--highlight-color");
  await page.goto(`/print/page/${note.id}`);
  await expect(page.locator("article mark")).toHaveCSS("background-color", "rgb(191, 219, 254)");
  await page.goto("/app?page=invalid-or-deleted-page");
  await expect(page.locator(".workspace")).toBeVisible();
  await expect.poll(() => new URL(page.url()).searchParams.has("page")).toBe(false);
});
